import { spawn } from 'node:child_process';
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const [url = "http://localhost:5199/", out = "smoke.png", waitMs = "10000"] = process.argv.slice(2);
const chrome = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--remote-debugging-port=9333', '--window-size=1500,950', `--user-data-dir=${mkdtempSync(join(tmpdir(), 'cdp-'))}`, 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let ws;
for (let i = 0; i < 50; i++) { try { const list = await (await fetch('http://127.0.0.1:9333/json')).json(); const page = list.find((p) => p.type === 'page'); if (page) { ws = new WebSocket(page.webSocketDebuggerUrl); break; } } catch {} await sleep(200); }
await new Promise((r) => ws.addEventListener('open', r));
let id = 0; const pending = new Map(); const logs = [];
ws.addEventListener('message', (m) => { const d = JSON.parse(m.data); if (d.id && pending.has(d.id)) { pending.get(d.id)(d.result ?? d.error); pending.delete(d.id); } if (d.method === 'Runtime.consoleAPICalled') logs.push(d.params.args.map((a) => a.value ?? a.description).join(' ')); if (d.method === 'Runtime.exceptionThrown') logs.push('EXC ' + d.params.exceptionDetails.text + ' ' + (d.params.exceptionDetails.exception?.description ?? '')); });
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await send('Runtime.enable'); await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1500, height: 950, deviceScaleFactor: 1, mobile: false });
await send('Page.navigate', { url });
await sleep(3500);
const r = await send('Runtime.evaluate', { expression: 'JSON.stringify(document.getElementById("start-btn").getBoundingClientRect())', returnByValue: true });
const b = JSON.parse(r.result.value);
const x = b.x + b.width / 2, y = b.y + b.height / 2;
for (const type of ['mouseMoved', 'mousePressed', 'mouseReleased']) await send('Input.dispatchMouseEvent', { type, x, y, button: 'left', clickCount: 1 });
await sleep(Number(waitMs));
const state = await send('Runtime.evaluate', { expression: 'JSON.stringify({ start: !!document.getElementById("start"), btn: document.getElementById("start-btn")?.textContent, canvas: document.querySelectorAll("#stage canvas").length, overlay: document.getElementById("overlay")?.style.display })', returnByValue: true });
console.log('state', state.result?.value);
const shot = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync(out, Buffer.from(shot.data, 'base64'));
console.log(logs.filter((l) => !/vite/.test(l)).slice(0, 10).join('\n'));
ws.close(); chrome.kill();
process.exit(0);
